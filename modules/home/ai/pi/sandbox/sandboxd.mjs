#!/usr/bin/env node
/**
 * pi-sandbox supervisor.
 *
 * Runs inside the sandbox container as its entry point and serves requests from
 * the Pi host process (the `sandbox` extension) over newline-delimited JSON on
 * stdin/stdout. The sandbox, not the extension, is the authority on paths: every
 * operation below is a plain filesystem or process call, so a path that is not
 * mounted into the container simply does not exist here.
 *
 *   -> {"id":1,"op":"read","path":"/home/u/proj/a.ts"}
 *   <- {"id":1,"ok":true,"data":"<base64>"}
 *   -> {"id":2,"op":"exec","command":"npm test","cwd":"/home/u/proj","timeoutMs":60000}
 *   <- {"id":2,"event":"data","stream":"stdout","data":"<base64>"}
 *   <- {"id":2,"event":"exit","code":0}
 *
 * Only `PI_*` variables from a request are forwarded to commands; host
 * environment variables never reach the sandbox.
 */
import { spawn } from "node:child_process";
import fs from "node:fs";
import fsp from "node:fs/promises";
import path from "node:path";
import readline from "node:readline";

const MAX_READ_BYTES = 64 * 1024 * 1024;
const KILL_GRACE_MS = 2000;

/** Environment passed to sandboxed commands, in addition to any request `PI_*` vars. */
const BASE_ENV_KEYS = [
  "PATH",
  "HOME",
  "TMPDIR",
  "TMP",
  "TEMP",
  "LANG",
  "LC_ALL",
  "TERM",
  "SSL_CERT_FILE",
  "NIX_SSL_CERT_FILE",
  "XDG_CACHE_HOME",
  "XDG_CONFIG_HOME",
  "UV_CACHE_DIR",
  "GIT_OPTIONAL_LOCKS",
  "PYTHONDONTWRITEBYTECODE",
  "USER",
  "LOGNAME",
  "SHELL",
  "HOSTNAME",
];

/**
 * Pi injects session metadata as `PI_*`; pass it through so tools that ask which
 * model is running still work. `PI_SESSION_FILE` names a host path that does not
 * exist in the sandbox, so it is dropped rather than leaked.
 */
const REQUEST_ENV = /^PI_[A-Z0-9_]+$/;
const REQUEST_ENV_DENY = new Set(["PI_SESSION_FILE"]);

/** @type {Map<number, {child: import("node:child_process").ChildProcess, timedOut: boolean, killTimer?: NodeJS.Timeout}>} */
const running = new Map();
let nextRunId = 1;

function write(message) {
  process.stdout.write(`${JSON.stringify(message)}\n`);
}

function reply(id, extra) {
  write({ id, ok: true, ...extra });
}

function fail(id, error) {
  write({
    id,
    ok: false,
    error: {
      code: typeof error?.code === "string" ? error.code : "EIO",
      message: error instanceof Error ? error.message : String(error),
    },
  });
}

function baseEnv() {
  const env = {};
  for (const key of BASE_ENV_KEYS) {
    const value = process.env[key];
    if (typeof value === "string") env[key] = value;
  }
  return env;
}

function commandEnv(requestEnv) {
  const env = baseEnv();
  if (requestEnv && typeof requestEnv === "object") {
    for (const [key, value] of Object.entries(requestEnv)) {
      if (typeof value !== "string") continue;
      if (!REQUEST_ENV.test(key) || REQUEST_ENV_DENY.has(key)) continue;
      env[key] = value;
    }
  }
  return env;
}

/**
 * Make the sandbox PATH visible to login shells too. Pi runs commands with
 * `bash -c`, which inherits the environment directly, but Alpine's /etc/profile
 * resets PATH for `bash -l`, so prepend our value there as well.
 */
function installProfilePath() {
  const dir = "/etc/profile.d";
  const file = path.join(dir, "10-pi-sandbox-path.sh");
  const sandboxPath = process.env.PATH;
  if (!sandboxPath) return;
  try {
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(
      file,
      `# Generated by pi-sandbox: keep the sandbox tool path available to login shells.\nexport PATH=${JSON.stringify(sandboxPath)}:"$PATH"\n`,
      // The container entry point normally writes this already; "wx" keeps that
      // version authoritative and only falls back when it is absent.
      { mode: 0o644, flag: "wx" },
    );
  } catch {
    // The container filesystem is expected to be writable; ignore failures so a
    // read-only rootfs still yields a working (if less convenient) sandbox.
  }
}

function stopRun(runId, signal) {
  const run = running.get(runId);
  if (!run) return;
  try {
    if (run.child.pid) process.kill(-run.child.pid, signal);
    else run.child.kill(signal);
  } catch {
    try {
      run.child.kill(signal);
    } catch {
      // Already gone.
    }
  }
}

async function readFileBase64(filePath) {
  const stat = await fsp.stat(filePath);
  if (stat.isDirectory()) {
    const error = new Error(`EISDIR: illegal operation on a directory, read '${filePath}'`);
    error.code = "EISDIR";
    throw error;
  }
  if (stat.size > MAX_READ_BYTES) {
    const error = new Error(`file too large to read (${stat.size} bytes > ${MAX_READ_BYTES})`);
    error.code = "EFBIG";
    throw error;
  }
  const buffer = await fsp.readFile(filePath);
  return buffer.toString("base64");
}

async function statInfo(target) {
  const stat = await fsp.stat(target);
  return {
    isDirectory: stat.isDirectory(),
    isFile: stat.isFile(),
    isSymbolicLink: stat.isSymbolicLink(),
    size: stat.size,
    mode: stat.mode,
    mtimeMs: stat.mtimeMs,
  };
}

function startExec(id, request) {
  const runId = nextRunId++;
  const cwd = typeof request.cwd === "string" && request.cwd ? request.cwd : process.env.HOME || "/tmp";
  const shell = process.env.SANDBOX_SHELL || "/bin/sh";
  const child = spawn(shell, ["-c", String(request.command ?? "")], {
    cwd,
    env: commandEnv(request.env),
    detached: true,
    stdio: ["ignore", "pipe", "pipe"],
  });

  const run = { child, timedOut: false };
  running.set(runId, run);
  reply(id, { runId });

  let timeoutTimer;
  const timeoutMs = Number(request.timeoutMs);
  if (Number.isFinite(timeoutMs) && timeoutMs > 0) {
    timeoutTimer = setTimeout(() => {
      run.timedOut = true;
      stopRun(runId, "SIGKILL");
    }, timeoutMs);
  }

  const emit = (stream, chunk) => {
    write({ id, event: "data", stream, data: chunk.toString("base64") });
  };
  child.stdout?.on("data", (chunk) => emit("stdout", chunk));
  child.stderr?.on("data", (chunk) => emit("stderr", chunk));

  child.on("error", (error) => {
    clearTimeout(timeoutTimer);
    running.delete(runId);
    write({ id, event: "exit", code: null, error: error.message });
  });

  child.on("close", (code, signal) => {
    clearTimeout(timeoutTimer);
    running.delete(runId);
    write({
      id,
      event: "exit",
      code,
      signal: signal ?? null,
      timedOut: run.timedOut === true,
    });
  });
}

async function handle(request) {
  const { id } = request;
  switch (request.op) {
    case "ping":
      reply(id, { cwd: process.cwd(), uid: process.getuid?.() ?? null, gid: process.getgid?.() ?? null });
      return;

    case "read":
      reply(id, { data: await readFileBase64(String(request.path)) });
      return;

    case "write":
      await fsp.writeFile(String(request.path), Buffer.from(String(request.data ?? ""), "base64"));
      reply(id, {});
      return;

    case "mkdir":
      await fsp.mkdir(String(request.path), { recursive: request.recursive !== false });
      reply(id, {});
      return;

    case "access": {
      const mode = request.write ? fs.constants.R_OK | fs.constants.W_OK : fs.constants.R_OK;
      await fsp.access(String(request.path), mode);
      reply(id, {});
      return;
    }

    case "stat":
      reply(id, await statInfo(String(request.path)));
      return;

    case "lstat": {
      const stat = await fsp.lstat(String(request.path));
      reply(id, {
        isDirectory: stat.isDirectory(),
        isFile: stat.isFile(),
        isSymbolicLink: stat.isSymbolicLink(),
        size: stat.size,
        mode: stat.mode,
        mtimeMs: stat.mtimeMs,
      });
      return;
    }

    case "readdir":
      reply(id, { entries: await fsp.readdir(String(request.path)) });
      return;

    case "realpath":
      reply(id, { path: await fsp.realpath(String(request.path)) });
      return;

    case "exec":
      startExec(id, request);
      return;

    case "kill":
      stopRun(Number(request.runId), typeof request.signal === "string" ? request.signal : "SIGKILL");
      reply(id, {});
      return;

    case "shutdown":
      reply(id, {});
      shutdown();
      return;

    default:
      fail(id, new Error(`unknown op: ${String(request.op)}`));
  }
}

let shuttingDown = false;
function shutdown() {
  if (shuttingDown) return;
  shuttingDown = true;
  for (const runId of [...running.keys()]) stopRun(runId, "SIGTERM");
  setTimeout(() => {
    for (const runId of [...running.keys()]) stopRun(runId, "SIGKILL");
    process.exit(0);
  }, KILL_GRACE_MS).unref();
}

installProfilePath();

const lines = readline.createInterface({ input: process.stdin });
lines.on("line", (line) => {
  const trimmed = line.trim();
  if (!trimmed) return;
  let request;
  try {
    request = JSON.parse(trimmed);
  } catch {
    return;
  }
  // Requests are handled concurrently: a long-running command must not block
  // file operations from the same session.
  handle(request).catch((error) => fail(request.id, error));
});

lines.on("close", () => shutdown());
process.on("SIGTERM", () => shutdown());
process.on("SIGINT", () => shutdown());
